// buildman generates the Linux man pages from internal/clispec (issue #45).
// The pages are generated, not hand-written: edit clispec and re-run.
//
// Usage:
//
//	go run ./tools/buildman                 # regenerate man/man1/*.1 in place
//	go run ./tools/buildman -check          # exit 1 if committed pages are stale
//	go run ./tools/buildman -dir DIR        # write/compare against DIR instead
//	go run ./tools/buildman -tarball OUT.tar.gz   # distributable man package
package main

import (
	"archive/tar"
	"bytes"
	"compress/gzip"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"

	"github.com/reihlinstinct/parcel-coverage-audit/internal/clispec"
)

const header = `.\" Generated by tools/buildman from internal/clispec; do not edit.`

func esc(s string) string {
	return strings.ReplaceAll(strings.ReplaceAll(s, `\`, `\e`), "-", `\-`)
}

func textLine(s string) string {
	if strings.HasPrefix(s, ".") || strings.HasPrefix(s, "'") {
		return `\&` + esc(s)
	}
	return esc(s)
}

func pageName(c clispec.Command) string {
	if c.Name == "" {
		return clispec.Program + ".1"
	}
	return clispec.Program + "-" + c.Name + ".1"
}

func title(c clispec.Command) string {
	return strings.TrimSuffix(pageName(c), ".1")
}

func render(c clispec.Command) string {
	var b strings.Builder
	b.WriteString(header + "\n")
	fmt.Fprintf(&b, ".TH %q \"1\" %q %q %q\n", esc(strings.ToUpper(title(c))), clispec.ManDate,
		clispec.Program+" "+clispec.Version, clispec.Manual)
	b.WriteString(".SH NAME\n")
	fmt.Fprintf(&b, "%s \\- %s\n", esc(title(c)), esc(c.Summary))
	b.WriteString(".SH SYNOPSIS\n")
	usage := c.Binary
	if c.Name == "support" {
		usage += " SUBCOMMAND"
	}
	for _, o := range c.Options {
		usage += " [-" + o.Name + " VALUE]"
	}
	b.WriteString(".B " + esc(usage) + "\n")
	b.WriteString(".SH DESCRIPTION\n")
	for _, para := range c.Details {
		b.WriteString(".PP\n" + textLine(para) + "\n")
	}
	if c.Name == "support" {
		b.WriteString(".SH SUBCOMMANDS\n")
		for _, sub := range clispec.SupportSubcommands {
			b.WriteString(".TP\n.B " + esc(sub) + "\n")
		}
	}
	if len(c.Options) > 0 {
		b.WriteString(".SH OPTIONS\n")
		for _, o := range c.Options {
			fmt.Fprintf(&b, ".TP\n.B \\-%s VALUE\n%s (default: %s)\n", esc(o.Name), textLine(o.Usage), esc(o.Def))
		}
	}
	if len(c.Examples) > 0 {
		b.WriteString(".SH EXAMPLES\n")
		for _, ex := range c.Examples {
			b.WriteString(".PP\n" + textLine(ex[0]) + "\n.RS\n" + textLine(ex[1]) + "\n.RE\n")
		}
	}
	b.WriteString(".SH EXIT STATUS\n.TP\n.B 0\nSuccess.\n.TP\n.B 1\nError (usage, input or audit failure).\n")
	b.WriteString(".SH SEE ALSO\n")
	var others []string
	for _, o := range clispec.Commands {
		if t := title(o); t != title(c) {
			others = append(others, t)
		}
	}
	for i, t := range others {
		comma := ","
		if i == len(others)-1 {
			comma = ""
		}
		fmt.Fprintf(&b, ".BR %s (1)%s\n", esc(t), comma)
	}
	b.WriteString(".BR man (1)\n")
	return b.String()
}

func renderAll() map[string]string {
	out := map[string]string{}
	for _, c := range clispec.Commands {
		out[pageName(c)] = render(c)
	}
	return out
}

func main() {
	check := flag.Bool("check", false, "exit 1 if committed pages are stale")
	dir := flag.String("dir", "man/man1", "write/compare against DIR")
	tarball := flag.String("tarball", "", "also write a distributable .tar.gz")
	flag.Parse()

	pages := renderAll()
	if *check {
		var stale []string
		existing := map[string]string{}
		matches, _ := filepath.Glob(filepath.Join(*dir, clispec.Program+"*.1"))
		for _, m := range matches {
			b, err := os.ReadFile(m)
			if err == nil {
				existing[filepath.Base(m)] = string(b)
			}
		}
		for name, body := range pages {
			if existing[name] != body {
				stale = append(stale, name)
			}
			delete(existing, name)
		}
		for name := range existing {
			stale = append(stale, name+" (untracked by clispec)")
		}
		if len(stale) > 0 {
			sort.Strings(stale)
			fmt.Println("stale man pages:", strings.Join(stale, ", "))
			os.Exit(1)
		}
		fmt.Printf("OK: %d man page(s) up to date\n", len(pages))
		return
	}

	if err := os.MkdirAll(*dir, 0o755); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	names := make([]string, 0, len(pages))
	for name := range pages {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		if err := os.WriteFile(filepath.Join(*dir, name), []byte(pages[name]), 0o644); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
	}
	fmt.Printf("wrote %d man page(s) to %s\n", len(pages), *dir)

	if *tarball != "" {
		// Deterministic: tar in memory, gzipped with a zeroed header time.
		var raw bytes.Buffer
		tw := tar.NewWriter(&raw)
		for _, name := range names {
			body := []byte(pages[name])
			if err := tw.WriteHeader(&tar.Header{Name: "man1/" + name, Mode: 0o644, Size: int64(len(body))}); err != nil {
				fmt.Fprintln(os.Stderr, err)
				os.Exit(1)
			}
			if _, err := tw.Write(body); err != nil {
				fmt.Fprintln(os.Stderr, err)
				os.Exit(1)
			}
		}
		if err := tw.Close(); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		var out bytes.Buffer
		gz, _ := gzip.NewWriterLevel(&out, gzip.BestCompression)
		gz.ModTime = time.Time{} // zeroed mtime: identical pages, identical archive
		if _, err := gz.Write(raw.Bytes()); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		if err := gz.Close(); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		if err := os.WriteFile(*tarball, out.Bytes(), 0o644); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		fmt.Println("wrote tarball", *tarball)
	}
}
